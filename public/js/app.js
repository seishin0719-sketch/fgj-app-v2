function jumpTpl(name){
  closeModal();go('sc-tpl');
  // 名稱可能含全形／半形差異，先正規化再比對
  const norm=s=>s.replace(/／/g,'/').replace(/（[^）]*）/g,'').trim();
  const target=norm(name);
  const t=TEMPLATES.find(x=>norm(x.name)===target)
        || TEMPLATES.find(x=>norm(x.name).includes(target)||target.includes(norm(x.name)));
  if(t){curTplCat=t.cat;renderTpl();setTimeout(()=>openGen(t.id),220);}
  else toast('範本產生器準備中');
}

